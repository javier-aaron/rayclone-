function searchEmojis(query) {
  const q = String(query || '').trim().toLowerCase().replace(/^:|:$/g, '');
  if (!q) return [];

  const matches = [];
  for (const item of EMOJIS) {
    let score = 0;
    if (item.name.toLowerCase().startsWith(q)) score += 50;
    else if (item.name.toLowerCase().includes(q)) score += 30;

    for (const kw of item.keywords) {
      if (kw === q) score += 60;
      else if (kw.startsWith(q)) score += 40;
      else if (kw.includes(q)) score += 20;
    }

    if (score > 0) {
      matches.push({ item, score });
    }
  }

  matches.sort((a, b) => b.score - a.score);
  return matches.slice(0, 15).map(({ item }) => item);
}

